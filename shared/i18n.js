function detectar() {
  const pedidos = (typeof navigator !== 'undefined' && navigator.languages) || ['es'];
  for (const l of pedidos) {
    const corto = l.slice(0, 2).toLowerCase();
    if (TEXTOS[corto]) return corto;
  }
  return 'es';
}

export function idioma() {
  const elegido = obtener().idioma;
  return TEXTOS[elegido] ? elegido : detectar();
}

export function cambiarIdioma(codigo) {
  if (!TEXTOS[codigo]) return;
  obtener().idioma = codigo;
  guardar();
  aplicarTextos();
}

export function t(clave, vars = {}) {
  const dic = TEXTOS[idioma()];
  let texto = dic[clave] ?? TEXTOS.es[clave] ?? clave;
  for (const [k, v] of Object.entries(vars)) texto = texto.replaceAll(`{${k}}`, v);
  return texto;
}

export function nombreSabor(id) {
  return TEXTOS[idioma()].sabores[id] ?? id;
}

export function nombreHilo(id) {
  return TEXTOS[idioma()].hilos[id] ?? id;
}

export function nombreFruta(id) {
  return TEXTOS[idioma()].frutas[id] ?? id;
}

/** Pone el texto en todo elemento con data-t (y data-t-aria para etiquetas accesibles). */
export function aplicarTextos(raiz = document) {
  document.documentElement.lang = idioma();
  for (const el of raiz.querySelectorAll('[data-t]')) el.textContent = t(el.dataset.t);
  for (const el of raiz.querySelectorAll('[data-t-aria]')) el.setAttribute('aria-label', t(el.dataset.tAria));
  document.dispatchEvent(new CustomEvent('qhatu:idioma'));
}
