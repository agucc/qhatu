function detectar() {
  const pedidos = (typeof navigator !== 'undefined' && navigator.languages) || ['es'];
  for (const l of pedidos) {
    const corto = l.slice(0, 2).toLowerCase();
    if (TEXTOS[corto]) return corto;
  }
  return 'es';
}

export function idioma() {
  const elegido = obtener().idioma;
  return TEXTOS[elegido] ? elegido : detectar();
}

export function cambiarIdioma(codigo) {
  if (!TEXTOS[codigo]) return;
  obtener().idioma = codigo;
  guardar();
  aplicarTextos();
}

export function t(clave, vars = {}) {
  const dic = TEXTOS[idioma()];
  let texto = dic[clave] ?? TEXTOS.es[clave] ?? clave;
  for (const [k, v] of Object.entries(vars)) texto = texto.replaceAll(`{${k}}`, v);
  return texto;
}

