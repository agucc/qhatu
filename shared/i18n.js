/** Pone el texto en todo elemento con data-t (y data-t-aria para etiquetas accesibles). */
export function aplicarTextos(raiz = document) {
  document.documentElement.lang = idioma();
  for (const el of raiz.querySelectorAll('[data-t]')) el.textContent = t(el.dataset.t);
  for (const el of raiz.querySelectorAll('[data-t-aria]')) el.setAttribute('aria-label', t(el.dataset.tAria));
  document.dispatchEvent(new CustomEvent('qhatu:idioma'));
}
